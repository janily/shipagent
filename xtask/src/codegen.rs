use anyhow::{Context, Result, bail};
use std::{collections::BTreeMap, fs, path::Path, process::Command};

const NAMES: [&str; 3] = ["Message", "Session", "SessionEvent"];

pub(crate) fn run(check: bool) -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("workspace root")?;
    let temp = tempfile::tempdir()?;
    let status = Command::new(std::env::var_os("AGENTKIT_NODE").unwrap_or_else(|| "node".into()))
        .arg(root.join("tools/codegen/schema.mjs"))
        .arg("--out")
        .arg(temp.path())
        .status()
        .context("Run schema extraction; install Node >=22 and npm ci --prefix tools/codegen")?;
    if !status.success() {
        bail!("TypeScript schema extraction failed; no generated files changed");
    }
    let mut outputs = Vec::new();
    let mut definitions = BTreeMap::new();
    let mut event_types = std::collections::BTreeSet::new();
    for name in NAMES {
        let bytes = fs::read(temp.path().join(format!("{name}.json")))?;
        let mut normalized: serde_json::Value = serde_json::from_slice(&bytes)?;
        if name == "SessionEvent" {
            let variants = normalized["definitions"]["SessionEvent"]["anyOf"]
                .as_array()
                .context("SessionEvent union must use anyOf")?;
            for variant in variants {
                event_types.insert(
                    variant["properties"]["type"]["const"]
                        .as_str()
                        .context("SessionEvent must have a literal type discriminator")?
                        .to_owned(),
                );
            }
        }
        normalize_literals(&mut normalized);
        let schema: schemars::schema::RootSchema = serde_json::from_value(normalized)?;
        for (key, value) in schema.definitions {
            if let Some(previous) = definitions.insert(key.clone(), value.clone())
                && previous != value
            {
                bail!("Conflicting schema definition {key}");
            }
        }
        outputs.push((format!("tools/codegen/schemas/{name}.json"), bytes));
    }
    let mut settings = typify::TypeSpaceSettings::default();
    settings
        .with_struct_builder(false)
        .with_map_type("::std::collections::BTreeMap");
    let mut types = typify::TypeSpace::new(&settings);
    types
        .add_ref_types(definitions)
        .context("Convert JSON Schema with typify")?;
    let mut ast: syn::File = syn::parse2(types.to_stream())?;
    syn::visit_mut::VisitMut::visit_file_mut(&mut FieldSemantics, &mut ast);
    // Typify embeds entire JSON schemas in rustdoc. The reviewed schemas are
    // checked in separately; keep generated Rust focused on the actual types.
    for item in &mut ast.items {
        let attrs = match item {
            syn::Item::Struct(v) => Some(&mut v.attrs),
            syn::Item::Enum(v) => Some(&mut v.attrs),
            _ => None,
        };
        if let Some(attrs) = attrs {
            attrs.retain(|a| !a.path().is_ident("doc"));
        }
    }
    let event_types = serde_json::to_string(&event_types)?;
    let rust = format!(
        "// @generated by cargo xtask codegen; do not edit.\n// Source: pinned backend/mkagent; schemas in tools/codegen/schemas.\npub const SESSION_EVENT_TYPES: &[&str] = &{event_types};\n{}",
        prettyplease::unparse(&ast)
    );
    let rust = format!(
        "{rust}\nfn required_option<'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error> where D: ::serde::Deserializer<'de>, T: ::serde::Deserialize<'de> {{ <Option<T> as ::serde::Deserialize>::deserialize(deserializer) }}\n"
    );
    let rust_path = temp.path().join("generated.rs");
    fs::write(&rust_path, rust)?;
    let status = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .arg(&rust_path)
        .status()
        .context("rustfmt is required for reproducible generated Rust")?;
    if !status.success() {
        bail!("Formatting generated Rust failed");
    }
    outputs.push((
        "crates/agentkit-protocol/src/generated.rs".into(),
        fs::read(rust_path)?,
    ));
    publish(root, outputs, check)?;
    println!(
        "Protocol codegen {}: Message, Session, SessionEvent",
        if check { "verified" } else { "updated" }
    );
    Ok(())
}

// Typify collapses optional collections to empty collections. Preserve the TS
// distinction between an absent property and an explicit [] / {} as Option.
struct FieldSemantics;
impl syn::visit_mut::VisitMut for FieldSemantics {
    fn visit_field_mut(&mut self, field: &mut syn::Field) {
        let mut optional = false;
        for attr in &mut field.attrs {
            if !attr.path().is_ident("serde") {
                continue;
            }
            let Ok(mut metas) = attr.parse_args_with(
                syn::punctuated::Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated,
            ) else {
                continue;
            };
            for meta in &mut metas {
                if let syn::Meta::NameValue(value) = meta
                    && value.path.is_ident("skip_serializing_if")
                    && let syn::Expr::Lit(lit) = &mut value.value
                    && let syn::Lit::Str(name) = &mut lit.lit
                    && name.value().ends_with("::is_empty")
                {
                    *name = syn::LitStr::new("::std::option::Option::is_none", name.span());
                    optional = true;
                }
            }
            if let syn::Meta::List(list) = &mut attr.meta {
                list.tokens = quote::quote!(#metas);
            }
        }
        if optional {
            let ty = &field.ty;
            field.ty = syn::parse_quote!(::std::option::Option<#ty>);
        }
        let is_option = matches!(&field.ty, syn::Type::Path(path) if path.path.segments.last().is_some_and(|segment| segment.ident == "Option"));
        let has_default = field
            .attrs
            .iter()
            .filter(|attr| attr.path().is_ident("serde"))
            .any(|attr| {
                attr.parse_args_with(
                    syn::punctuated::Punctuated::<syn::Meta, syn::Token![,]>::parse_terminated,
                )
                .is_ok_and(|metas| metas.iter().any(|meta| meta.path().is_ident("default")))
            });
        if is_option && !has_default {
            // Serde otherwise accepts an absent required nullable property as None.
            field
                .attrs
                .push(syn::parse_quote!(#[serde(deserialize_with = "required_option")]));
        }
        syn::visit_mut::visit_field_mut(self, field);
    }
}

// ts-json-schema-generator emits draft-07 const; typify's draft-07 reader
// otherwise widens those to String, defeating event discriminators. A singleton
// enum has identical JSON Schema semantics and is supported by typify.
fn normalize_literals(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Object(object) => {
            if let Some(literal) = object.remove("const") {
                object.insert("enum".into(), serde_json::json!([literal]));
            }
            for child in object.values_mut() {
                normalize_literals(child);
            }
        }
        serde_json::Value::Array(array) => {
            for child in array {
                normalize_literals(child);
            }
        }
        _ => {}
    }
}

fn publish(root: &Path, outputs: Vec<(String, Vec<u8>)>, check: bool) -> Result<()> {
    let changed: Vec<_> = outputs
        .iter()
        .filter(|(path, bytes)| fs::read(root.join(path)).ok().as_ref() != Some(bytes))
        .collect();
    if check && !changed.is_empty() {
        bail!(
            "Generated protocol drift: {}. Run cargo xtask codegen and review the diff.",
            changed
                .iter()
                .map(|(p, _)| p.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    for (path, bytes) in changed {
        let path = root.join(path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(path, bytes)?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn drift_check_never_rewrites_changed_or_missing_artifacts() -> Result<()> {
        let root = tempfile::tempdir()?;
        let artifact = root.path().join("generated.rs");
        let outputs = || vec![("generated.rs".into(), b"expected".to_vec())];
        assert!(publish(root.path(), outputs(), true).is_err());
        assert!(!artifact.exists());
        fs::write(&artifact, "manual edit")?;
        assert!(publish(root.path(), outputs(), true).is_err());
        assert_eq!(fs::read_to_string(&artifact)?, "manual edit");
        publish(root.path(), outputs(), false)?;
        publish(root.path(), outputs(), true)?;
        assert_eq!(fs::read_to_string(&artifact)?, "expected");
        Ok(())
    }
}
